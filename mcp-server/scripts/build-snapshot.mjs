#!/usr/bin/env node
/**
 * Regenerates src/data/snapshot.ts from the app source in the parent repo.
 *
 * The snapshot is the offline fallback the server uses when GitHub is
 * unreachable. Run `npm run snapshot` after meaningful feature-data changes so
 * the fallback does not drift too far from the live tool.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const serverRoot = path.resolve(here, "..");
const appRoot = path.resolve(serverRoot, "..");

const featuresPath = path.join(appRoot, "src/data/features.ts");
const componentPath = path.join(appRoot, "src/components/PlanComparisonTool.tsx");

for (const p of [featuresPath, componentPath]) {
  if (!fs.existsSync(p)) {
    console.error(`Could not find ${p}. Run this from inside the se-slack-app-2 repo.`);
    process.exit(1);
  }
}

const { parseFeaturesModule, parseCategoryMap } = await import(
  path.join(serverRoot, "dist/data/parse.js")
).catch(() => {
  console.error("Build the server first: npm run build (then re-run npm run snapshot).");
  process.exit(1);
});

const { featureData, legacyAddOns } = parseFeaturesModule(fs.readFileSync(featuresPath, "utf8"));
const categories = parseCategoryMap(fs.readFileSync(componentPath, "utf8"));

const banner = `/**
 * AUTO-GENERATED by scripts/build-snapshot.mjs - do not edit by hand.
 *
 * Offline fallback used when the live GitHub sources cannot be reached.
 * Regenerate with: npm run build && npm run snapshot
 */

import type { CategoryMap, FeatureData, LegacyAddOns } from "../types.js";
`;

const body = `
export const SNAPSHOT_GENERATED_AT = ${JSON.stringify(new Date().toISOString())};

export const SNAPSHOT_FEATURE_DATA: FeatureData = ${JSON.stringify(featureData, null, 2)};

export const SNAPSHOT_LEGACY_ADD_ONS: LegacyAddOns = ${JSON.stringify(legacyAddOns, null, 2)};

export const SNAPSHOT_CATEGORIES: CategoryMap = ${JSON.stringify(categories, null, 2)};
`;

const outPath = path.join(serverRoot, "src/data/snapshot.ts");
fs.writeFileSync(outPath, banner + body);

console.log(
  `Wrote ${path.relative(serverRoot, outPath)} - ` +
    `${Object.keys(featureData.featureAvailability).length} features, ` +
    `${Object.keys(categories).length} categories.`,
);
